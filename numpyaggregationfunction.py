import numpy as np
a=np.array([10,20,30,40,50])
print(np.sum(a))#sum aggregation function
print(np.mean(a))#mean aggregation function
print(np.max(a))#max aggregation function
print(np.min(a))#min aggrgation function
print(np.std(a))#std aggregation function 
print(np.var(a))#var aggregation function

